const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const H = require('./lib/ui-harness.cjs');
const root = require('node:path').resolve(__dirname, '../common/src/main/resources/assets/cadeditor');
const zh = JSON.parse(fs.readFileSync(root + '/lang/zh_cn.json', 'utf8'));
const en = JSON.parse(fs.readFileSync(root + '/lang/en_us.json', 'utf8'));
const key = value => Object.keys(zh).find(k => zh[k] === value);
const z = H.create({data:{uiLocale:'zh_cn'}}), e = H.create({data:{uiLocale:'en_us'}});
assert.equal(z.c.Labels.slot.mainhand, '主手');
assert.equal(e.c.Labels.slot.mainhand, 'Main hand');
assert.equal(e.c.Labels.rarity[1].label, 'Uncommon');
assert.equal(e.doc.title, 'CAD Editor');
assert.equal(e.doc.documentElement.getAttribute('lang'), 'en-us');
assert.equal(H.create({data:{uiLocale:'fr_fr'}}).c.I18n.locale, 'en_us');
assert.equal(H.create().c.I18n.locale, 'zh_cn');
assert.equal(e.c.I18n.format('%2$s / %1$s / 100%%', ['$1%2$s', 'NaN']), 'NaN / $1%2$s / 100%');
assert.equal(e.c.I18n.format('%s / %s / %1$s', ['first','second']), 'first / second / first');
const extended = {oriel:{data:{uiLocale:'fr_fr'}}, EDATA:{}, EditorTextFields:[], EditorVanillaEnglish:[], EditorCatalogs:{en_us:{save:'Save',cancel:'Cancel'},fr_fr:{save:'Enregistrer'}}};
vm.runInNewContext(fs.readFileSync(root + '/ui/js/i18n.js','utf8'), extended);
assert.equal(extended.I18n.locale, 'fr_fr'); assert.equal(extended.I18n.t('save'), 'Enregistrer'); assert.equal(extended.I18n.t('cancel'),'Cancel');
const literal = '中文物品 %1$s <tag> \"';
assert.equal(e.c.I18n.t(key('已复制%1$s'), literal), 'Copied ' + literal);
const override = H.create({data:{uiLocale:'zh_cn',uiTranslations:{'cadeditor.ui.common.save':'资源包保存'}}});
assert.equal(override.c.I18n.t('cadeditor.ui.common.save'), '资源包保存');
assert.equal(override.c.I18n.en('cadeditor.ui.common.save'), 'Save');
assert.throws(() => override.c.I18n.withLanguage('en_us', () => { throw Error('expected'); }));
assert.equal(override.c.I18n.t('cadeditor.ui.common.save'), '资源包保存');
const raw = {}; vm.runInNewContext(fs.readFileSync(root + '/ui/js/data.js', 'utf8'), raw);
for (const h of [z,e]) {
  for (const field of ['pt','ipt','items','ikind','iblk']) assert.equal(JSON.stringify(h.c.EDATA[field]), JSON.stringify(raw.EDATA[field]), field + ' is data, not copy');
  const text = '{"名称":"玩家自己的中文 %1$s",unknown:{values:[B;1b,2b],long:9223372036854775807L,special:Infinityd}}';
  assert.equal(h.c.nbtMerge(h.c.parseSnbt(text), h.c.nbtParse(text)), text, 'typed NBT and user Chinese are literal');
  const about = h.doc.createElement('div'); h.c.Prefs.about = {version:'0.99.8'}; h.c.aboutSection(about);
  assert.doesNotMatch(about.textContent, /[㐀-鿿]/u);
  assert.match(about.textContent, /305562948/); assert.match(about.textContent, /Rinorsi/);
  const toasts = []; h.c.toast = text => toasts.push(text); h.c.Prefs.hostClip = true;
  about.querySelectorAll('.k-btn').find(b => b.textContent === 'Copy group ID').click();
  assert.equal(toasts[0], 'Copied QQ group ID');
  assert.equal(h.sent.find(([channel]) => channel === 'clipboard')[1].text, '305562948');
  h.c.Prefs.hostClip = false;
  about.querySelectorAll('.k-btn').find(b => b.textContent === 'Copy group ID').click();
  assert.doesNotMatch(h.root.querySelector('.k-modal').textContent, /[㐀-鿿]/u, 'manual copy remains English');
}
assert.equal(e.c.LABEL_ICON[e.c.I18n.t(key('声音'))], 'music', 'label-keyed icon maps work in English');
assert.equal(e.c.WORLD_SEC_ICON[e.c.I18n.t(key('玩家皮肤'))], 'user');
assert.equal(e.c.EDATA.iname.diamond_sword, 'Diamond Sword', 'preview fallback uses real Minecraft English');
assert.equal(e.c.EDATA.enchants.find(x => x.id === 'aqua_affinity').name, 'Aqua Affinity');
assert.doesNotMatch(e.c.EDATA.comps.map(x => x.name + x.desc).join(''), /[㐀-鿿]/u);
const note = '改进与修复：盔甲架姿势实时预览';
assert.equal(e.c.releaseNoteText(note).textContent, note, 'Chinese changelog content is not translated');
console.log('PASS i18n: first paint, fallback, resource overrides, About/copy, Chinese notes, game names and typed user data');
