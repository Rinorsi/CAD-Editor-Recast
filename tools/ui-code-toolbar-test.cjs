const assert = require('node:assert/strict'), fs = require('node:fs');
const H = require('./lib/ui-harness.cjs');
H.Element.prototype.setTextHighlights = function(source) { assert.equal(source, this.value); return true; };
const {c, doc} = H.create();
c.snd = () => {}; c.toast = () => {}; c.Reg.meta = {};
c.Store.open({id:'minecraft:stone',count:1,comps:{custom_data:c.parseSnbt('{precise:9007199254740993L}')},removed:{}},true);
c.rebuild(); c.UI.tab = 'item-stack'; c.UI.cmdFmt = 'snbt'; c.drawTabbar(); c.drawTabBody();
const tools = doc.getElementById('edtools'), body = doc.getElementById('edbody');
const ta = body.querySelector('textarea'), source = ta.value;
assert.deepEqual(Array.from(tools.querySelector('.ed-code-modes').children, e => e.textContent), ['命令','SNBT','JSON']);
const actions = tools.querySelector('.ed-code-actions'), reload = tools.querySelector('.kc-reload');
assert.equal(reload.parentNode, tools, 'reload stays outside the scrolling actions');
assert.equal(body.querySelector('.kc-reload'), null, 'reload does not cover or displace code');
for (const action of ['format','compact','copy']) {
  const button = Array.from(actions.querySelectorAll('.k-btn')).find(e => e.getAttribute('data-code-action') === action);
  assert(button, action + ' remains accessible');
  assert(button.getAttribute('aria-label'), action + ' has a name');
  assert.equal(button.textContent, '', action + ' is compact icon-only');
}
let copied; c.copyText = text => copied = text;
const click = action => Array.from(actions.querySelectorAll('.k-btn')).find(e => e.getAttribute('data-code-action') === action).fire('click');
click('copy'); assert.equal(copied, source);
click('compact'); assert(!ta.value.includes(String.fromCharCode(10))); assert(ta.value.includes('9007199254740993L'));
click('format'); assert(ta.value.includes(String.fromCharCode(10))); assert(ta.value.includes('9007199254740993L'));
ta.selectionStart = 5; ta.selectionEnd = 12; ta.scrollTop = 20;
Array.from(actions.querySelectorAll('.k-btn')).find(e=>e.textContent==='A+').fire('click');
assert.equal(body.querySelector('textarea'), ta);
assert.equal(ta.selectionStart, 5); assert.equal(ta.selectionEnd, 12); assert.equal(ta.scrollTop, 20);
ta.value = '{id:'; ta.fire('input'); assert(c.itemRawBlocked());
c.UI.cmdFmt = 'json'; c.drawTabBody(); c.UI.cmdFmt = 'snbt'; c.drawTabBody();
assert.equal(body.querySelector('textarea'), ta); assert.equal(ta.value, '{id:');
assert.equal(tools.querySelectorAll('.kc-reload').length, 1);
assert.equal(tools.querySelector('.kc-reload'), reload); reload.fire('click');
assert(!c.itemRawBlocked()); assert.equal(ta.value,c.stackSnbt(c.Store.doc()));
const css = fs.readFileSync('common/src/main/resources/assets/cadeditor/ui/editor.css','utf8');
assert(/\.ed-code-actions\s*\{[^}]*min-width:\s*0[^}]*overflow-x:\s*auto/.test(css));
assert(/\.kc-surface \.kc-ta\s*\{\s*padding-top:\s*4px/.test(css));
assert(!/\.kc-reload\s*\{[^}]*position:\s*absolute/.test(css));
console.log('PASS compact toolbar: format/copy/typed values, native textarea continuity, invalid buffer, fixed refresh, independent scrolling');
