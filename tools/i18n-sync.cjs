// Canonical translations live in Minecraft lang/*.json. Run after editing either catalog.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const root = path.resolve(__dirname, '..');
const assets = path.join(root, 'common/src/main/resources/assets/cadeditor');
const catalogs = {};
for (const file of fs.readdirSync(path.join(assets, 'lang')).filter(f => /^[a-z0-9_]{2,32}\.json$/.test(f)).sort()) {
  catalogs[file.slice(0,-5)] = JSON.parse(fs.readFileSync(path.join(assets, 'lang', file), 'utf8'));
}
const zh = catalogs.zh_cn, en = catalogs.en_us;
function sources(directory) {
  return fs.readdirSync(directory, {withFileTypes:true}).flatMap(entry => entry.isDirectory() ? sources(path.join(directory,entry.name)) : [path.join(directory,entry.name)]);
}
for (const file of sources(path.join(assets, 'ui/js')).filter(f => f.endsWith('.js') && !f.endsWith('i18n-catalogs.js')).concat(sources(path.join(root, 'common/src/main/java')).filter(f => f.endsWith('.java')))) {
  const source = fs.readFileSync(file,'utf8');
  for (const match of source.matchAll(/(?:I18n\.(?:t|en)|EditorI18n\.tr)\(\s*["']([^"']+)["']/g)) {
    if (!Object.prototype.hasOwnProperty.call(zh, match[1])) throw new Error('Missing translation in ' + file + ': ' + match[1]);
  }
}
function placeholders(text) { let i=0; return (Array.from(text.matchAll(/%%|%(?:([1-9][0-9]*)\$)?s/g), m => m[0] === '%%' ? '%%' : '%' + (m[1] || ++i) + '$s')).sort().join('|'); }
if (Object.keys(zh).sort().join() !== Object.keys(en).sort().join()) throw new Error('Language catalog keys differ');
for (const key of Object.keys(zh)) {
  if (typeof zh[key] !== 'string' || typeof en[key] !== 'string' || !en[key].trim()) throw new Error('Invalid translation: ' + key);
  if (placeholders(zh[key]) !== placeholders(en[key])) throw new Error('Translation placeholders differ: ' + key);
  if (/[\u3400-\u9fff]/u.test(en[key])) throw new Error('Untranslated English entry: ' + key);
  if (/^\(function\s*\(/.test(zh[key])) throw new Error('Executable code must not be a translation template: ' + key);
}
for (const [locale, catalog] of Object.entries(catalogs)) for (const [key, value] of Object.entries(catalog)) {
  if (!Object.prototype.hasOwnProperty.call(en, key)) throw new Error('Unknown key in ' + locale + ': ' + key);
  if (typeof value !== 'string' || !value.trim() || placeholders(value) !== placeholders(en[key])) throw new Error('Invalid translation in ' + locale + ': ' + key);
}
const fields = JSON.parse(fs.readFileSync(path.join(__dirname, 'i18n-data-fields.json'), 'utf8'));
const ctx = {};
vm.runInNewContext(fs.readFileSync(path.join(assets, 'ui/js/data.js'), 'utf8'), ctx);
for (const field of fields) {
  const value = field.path.reduce((v, k) => v == null ? undefined : v[k], ctx.EDATA);
  if (typeof value !== 'string' || value.replace(/%/g, '%%') !== zh[field.key]) throw new Error('Stale editor metadata binding: ' + field.path.join('.'));
}
const frontend = {};
for (const locale of Object.keys(catalogs)) frontend[locale] = Object.fromEntries(Object.entries(catalogs[locale]).filter(([key]) => /^cadeditor\.(ui|data)\./.test(key)));
const vanilla = JSON.parse(fs.readFileSync(path.join(__dirname, 'i18n-vanilla-en.json'), 'utf8'));
const output = '// Generated by tools/i18n-sync.cjs; edit lang/*.json instead.\nvar EditorCatalogs = ' + JSON.stringify(frontend) + ';\nvar EditorTextFields = ' + JSON.stringify(fields) + ';\nvar EditorVanillaEnglish = ' + JSON.stringify(vanilla.bindings) + ';\n';
const destination = path.join(assets, 'ui/js/i18n-catalogs.js');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(destination) || fs.readFileSync(destination, 'utf8') !== output) throw new Error('Run node tools/i18n-sync.cjs to update UI catalogs');
} else fs.writeFileSync(destination, output);
console.log('i18n: ' + Object.keys(zh).length + ' matching keys; ' + fields.length + ' editor metadata fields');
